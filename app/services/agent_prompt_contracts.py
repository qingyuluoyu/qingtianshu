def _requested_fact_count(value: Any) -> int | None:
    text = str(value or "").replace(" ", "")
    match = re.search(r"([1-5一二两三四五])(?:个|项|件)事实", text)
    if match is None:
        return None
    token = match.group(1)
    if token.isdigit():
        return int(token)
    return {"一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5}[token]


def _asks_for_reassessment_conditions(value: Any) -> bool:
    text = str(value or "")
    return any(
        term in text
        for term in (
            "失效条件",
            "不成立条件",
            "什么时候需要重新判断",
            "何时需要重新判断",
            "需要重新判断的情况",
            "什么情况会推翻",
            "哪些情况会推翻",
            "什么会推翻",
        )
    )


